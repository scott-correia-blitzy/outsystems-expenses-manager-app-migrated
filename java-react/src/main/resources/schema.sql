-- Runs on every start, so every statement must be idempotent.

-- ORDER is reserved in H2, hence the quoted "Order" column in the static tables.
CREATE TABLE IF NOT EXISTS Currency (
    Id INT NOT NULL,
    Label VARCHAR(50) NOT NULL,
    "Order" INT NOT NULL,
    Is_Active BOOLEAN NOT NULL,
    CONSTRAINT PK_Currency PRIMARY KEY (Id)
);

CREATE TABLE IF NOT EXISTS Status (
    Id INT NOT NULL,
    Label VARCHAR(50) NOT NULL,
    "Order" INT NOT NULL,
    Is_Active BOOLEAN NOT NULL,
    CONSTRAINT PK_Status PRIMARY KEY (Id)
);

CREATE TABLE IF NOT EXISTS ExpenseType (
    Id INT NOT NULL,
    Label VARCHAR(50) NOT NULL,
    "Order" INT NOT NULL,
    Is_Active BOOLEAN NOT NULL,
    CONSTRAINT PK_ExpenseType PRIMARY KEY (Id)
);

CREATE TABLE IF NOT EXISTS EarningType (
    Id INT NOT NULL,
    Label VARCHAR(50) NOT NULL,
    "Order" INT NOT NULL,
    Is_Active BOOLEAN NOT NULL,
    CONSTRAINT PK_EarningType PRIMARY KEY (Id)
);

CREATE TABLE IF NOT EXISTS BlogPost (
    Id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    Title VARCHAR(50),
    Description VARCHAR(10000),
    CreatedBy BIGINT,
    UpdatedBy BIGINT,
    CreatedOn TIMESTAMP,
    IsActive BOOLEAN,
    UpdatedOn TIMESTAMP,
    CONSTRAINT PK_BlogPost PRIMARY KEY (Id)
);
CREATE INDEX IF NOT EXISTS BlogPost_AutoIndex_CreatedBy ON BlogPost (CreatedBy);
CREATE INDEX IF NOT EXISTS BlogPost_AutoIndex_UpdatedBy ON BlogPost (UpdatedBy);

-- SubmitedBy and SubmitedOn keep the legacy spelling.
CREATE TABLE IF NOT EXISTS ExpenseReport (
    Id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    Code VARCHAR(50),
    Title VARCHAR(50),
    StatusId INT,
    SubmitedBy BIGINT,
    CreatedOn TIMESTAMP,
    CreatedBy BIGINT,
    UpdatedBy BIGINT,
    UpdatedOn TIMESTAMP,
    IsActive BOOLEAN,
    SubmitedOn TIMESTAMP,
    ProcessedOn TIMESTAMP,
    CONSTRAINT PK_ExpenseReport PRIMARY KEY (Id)
);
CREATE INDEX IF NOT EXISTS ExpenseReport_AutoIndex_StatusId ON ExpenseReport (StatusId);
CREATE UNIQUE INDEX IF NOT EXISTS ExpenseReport_UniqueIndex_ReportCode ON ExpenseReport (Code);
CREATE INDEX IF NOT EXISTS ExpenseReport_AutoIndex_UpdatedBy ON ExpenseReport (UpdatedBy);
CREATE INDEX IF NOT EXISTS ExpenseReport_AutoIndex_SubmitedBy ON ExpenseReport (SubmitedBy);
CREATE INDEX IF NOT EXISTS ExpenseReport_AutoIndex_CreatedBy ON ExpenseReport (CreatedBy);
-- Foreign keys follow their indexes so H2 backs each one with the named index instead of creating a duplicate.
ALTER TABLE ExpenseReport ADD CONSTRAINT IF NOT EXISTS FK_ExpenseReport_StatusId FOREIGN KEY (StatusId) REFERENCES Status (Id);

CREATE TABLE IF NOT EXISTS EarningReport (
    Id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    Code VARCHAR(50),
    Title VARCHAR(50),
    StatusId INT,
    SubmitedBy BIGINT,
    CreatedOn TIMESTAMP,
    CreatedBy BIGINT,
    UpdatedBy BIGINT,
    UpdatedOn TIMESTAMP,
    IsActive BOOLEAN,
    SubmitedOn TIMESTAMP,
    ProcessedOn TIMESTAMP,
    CONSTRAINT PK_EarningReport PRIMARY KEY (Id)
);
CREATE INDEX IF NOT EXISTS EarningReport_AutoIndex_UpdatedBy ON EarningReport (UpdatedBy);
CREATE INDEX IF NOT EXISTS EarningReport_AutoIndex_CreatedBy ON EarningReport (CreatedBy);
CREATE UNIQUE INDEX IF NOT EXISTS EarningReport_UniqueIndex_ReportCode ON EarningReport (Code);
CREATE INDEX IF NOT EXISTS EarningReport_AutoIndex_StatusId ON EarningReport (StatusId);
CREATE INDEX IF NOT EXISTS EarningReport_AutoIndex_SubmitedBy ON EarningReport (SubmitedBy);
ALTER TABLE EarningReport ADD CONSTRAINT IF NOT EXISTS FK_EarningReport_StatusId FOREIGN KEY (StatusId) REFERENCES Status (Id);

CREATE TABLE IF NOT EXISTS Expense (
    Id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    Date DATE,
    Title VARCHAR(50),
    Description VARCHAR(1500),
    ExpenseTypeId INT,
    Distance DECIMAL(37,8),
    Amount DECIMAL(19,4),
    CurrencyId INT,
    AmountInEuros DECIMAL(19,4),
    ExpenseReportId BIGINT,
    CreatedBy BIGINT,
    CreatedOn TIMESTAMP,
    UpdatedBy BIGINT,
    UpdatedOn TIMESTAMP,
    IsActive BOOLEAN,
    CONSTRAINT PK_Expense PRIMARY KEY (Id)
);
CREATE INDEX IF NOT EXISTS Expense_AutoIndex_CurrencyId ON Expense (CurrencyId);
CREATE INDEX IF NOT EXISTS Expense_AutoIndex_CreatedBy ON Expense (CreatedBy);
CREATE INDEX IF NOT EXISTS Expense_AutoIndex_UpdatedBy ON Expense (UpdatedBy);
CREATE INDEX IF NOT EXISTS Expense_AutoIndex_ExpenseReportId ON Expense (ExpenseReportId);
CREATE INDEX IF NOT EXISTS Expense_AutoIndex_ExpenseTypeId ON Expense (ExpenseTypeId);
ALTER TABLE Expense ADD CONSTRAINT IF NOT EXISTS FK_Expense_ExpenseTypeId FOREIGN KEY (ExpenseTypeId) REFERENCES ExpenseType (Id);
ALTER TABLE Expense ADD CONSTRAINT IF NOT EXISTS FK_Expense_CurrencyId FOREIGN KEY (CurrencyId) REFERENCES Currency (Id);
ALTER TABLE Expense ADD CONSTRAINT IF NOT EXISTS FK_Expense_ExpenseReportId FOREIGN KEY (ExpenseReportId) REFERENCES ExpenseReport (Id) ON DELETE CASCADE;

CREATE TABLE IF NOT EXISTS Earning (
    Id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    Date DATE,
    Title VARCHAR(50),
    Description VARCHAR(1500),
    Distance DECIMAL(37,8),
    Amount DECIMAL(19,4),
    CurrencyId INT,
    AmountInEuros DECIMAL(19,4),
    CreatedBy BIGINT,
    CreatedOn TIMESTAMP,
    UpdatedBy BIGINT,
    UpdatedOn TIMESTAMP,
    IsActive BOOLEAN,
    EarningTypeId INT,
    EarningReportId BIGINT,
    CONSTRAINT PK_Earning PRIMARY KEY (Id)
);
CREATE INDEX IF NOT EXISTS Earning_AutoIndex_EarningTypeId ON Earning (EarningTypeId);
CREATE INDEX IF NOT EXISTS Earning_AutoIndex_CreatedBy ON Earning (CreatedBy);
CREATE INDEX IF NOT EXISTS Earning_AutoIndex_EarningReportId ON Earning (EarningReportId);
CREATE INDEX IF NOT EXISTS Earning_AutoIndex_CurrencyId ON Earning (CurrencyId);
CREATE INDEX IF NOT EXISTS Earning_AutoIndex_UpdatedBy ON Earning (UpdatedBy);
ALTER TABLE Earning ADD CONSTRAINT IF NOT EXISTS FK_Earning_CurrencyId FOREIGN KEY (CurrencyId) REFERENCES Currency (Id);
ALTER TABLE Earning ADD CONSTRAINT IF NOT EXISTS FK_Earning_EarningTypeId FOREIGN KEY (EarningTypeId) REFERENCES EarningType (Id);
ALTER TABLE Earning ADD CONSTRAINT IF NOT EXISTS FK_Earning_EarningReportId FOREIGN KEY (EarningReportId) REFERENCES EarningReport (Id) ON DELETE CASCADE;

CREATE TABLE IF NOT EXISTS InvoiceExpense (
    Id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    Content BLOB,
    Filename VARCHAR(50),
    Filetype VARCHAR(50),
    Datetime TIMESTAMP,
    CONSTRAINT PK_InvoiceExpense PRIMARY KEY (Id),
    CONSTRAINT FK_InvoiceExpense_Id FOREIGN KEY (Id) REFERENCES Expense (Id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS InvoiceEarning (
    Id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    Content BLOB,
    Filename VARCHAR(50),
    Filetype VARCHAR(50),
    Datetime TIMESTAMP,
    CONSTRAINT PK_InvoiceEarning PRIMARY KEY (Id),
    CONSTRAINT FK_InvoiceEarning_Id FOREIGN KEY (Id) REFERENCES Earning (Id) ON DELETE CASCADE
);

-- CreatedBy, UpdatedBy and SubmitedBy store AppUser ids without a foreign key.
CREATE TABLE IF NOT EXISTS AppUser (
    Id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    Username VARCHAR(250) NOT NULL,
    Name VARCHAR(250),
    PasswordHash VARCHAR(100) NOT NULL,
    CONSTRAINT PK_AppUser PRIMARY KEY (Id)
);
CREATE UNIQUE INDEX IF NOT EXISTS AppUser_UniqueIndex_Username ON AppUser (Username);

CREATE TABLE IF NOT EXISTS AppUserRole (
    UserId BIGINT NOT NULL,
    Role VARCHAR(20) NOT NULL,
    CONSTRAINT PK_AppUserRole PRIMARY KEY (UserId, Role),
    CONSTRAINT FK_AppUserRole_UserId FOREIGN KEY (UserId) REFERENCES AppUser (Id) ON DELETE CASCADE
);
